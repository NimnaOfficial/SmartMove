-- 2. MATERIALIZED VIEW: MV_MONTHLY_REVENUE
DROP MATERIALIZED VIEW MV_MONTHLY_REVENUE;

CREATE MATERIALIZED VIEW MV_MONTHLY_REVENUE
BUILD IMMEDIATE
REFRESH COMPLETE ON DEMAND
AS
SELECT 
    TO_CHAR(p.PAYMENT_DATE, 'YYYY-MM') AS REVENUE_MONTH,
    COUNT(b.BOOKING_ID)                AS TOTAL_BOOKINGS,
    SUM(p.AMOUNT)                      AS TOTAL_REVENUE
FROM PAYMENT p
JOIN BOOKING b ON p.BOOKING_ID = b.BOOKING_ID
WHERE p.STATUS = 'PAID'
GROUP BY TO_CHAR(p.PAYMENT_DATE, 'YYYY-MM');

-- Query materialized view:
SELECT * FROM MV_MONTHLY_REVENUE;


-- 3. STORED PROCEDURE: REPORT_REVENUE
CREATE OR REPLACE PROCEDURE REPORT_REVENUE (
    p_month         IN NUMBER,
    p_year          IN NUMBER,
    p_total_revenue OUT NUMBER
) AS
BEGIN
    SELECT NVL(SUM(AMOUNT), 0)
    INTO p_total_revenue
    FROM PAYMENT
    WHERE STATUS = 'PAID'
      AND EXTRACT(MONTH FROM PAYMENT_DATE) = p_month
      AND EXTRACT(YEAR FROM PAYMENT_DATE) = p_year;
END REPORT_REVENUE;
/


-- 4. REPORT 1: ROUTE USAGE & PASSENGER DENSITY (SQL WINDOW FUNCTION)
SELECT 
    r.ROUTE_ID,
    r.ORIGIN,
    r.DESTINATION,
    r.DISTANCE_KM,
    r.BASE_FARE,
    COUNT(b.BOOKING_ID) AS TOTAL_BOOKINGS,
    RANK() OVER (ORDER BY COUNT(b.BOOKING_ID) DESC) AS ROUTE_RANK
FROM ROUTE r
LEFT JOIN TRIP t ON r.ROUTE_ID = t.ROUTE_ID
LEFT JOIN BOOKING b ON t.TRIP_ID = b.TRIP_ID AND b.STATUS != 'CANCELLED'
GROUP BY r.ROUTE_ID, r.ORIGIN, r.DESTINATION, r.DISTANCE_KM, r.BASE_FARE
ORDER BY ROUTE_RANK;


-- 5. REPORT 2: FINANCIAL PERFORMANCE & REVENUE SUMMARY
SELECT 
    TO_CHAR(b.BOOKING_TIME, 'YYYY-MM') AS BOOKING_MONTH,
    COUNT(b.BOOKING_ID) AS TOTAL_BOOKINGS,
    SUM(CASE WHEN b.PAYMENT_STATUS = 'PAID' THEN b.TOTAL_FARE ELSE 0 END) AS COLLECTED_REVENUE,
    SUM(CASE WHEN b.PAYMENT_STATUS = 'UNPAID' THEN b.TOTAL_FARE ELSE 0 END) AS PENDING_REVENUE,
    SUM(b.TOTAL_FARE) AS GROSS_REVENUE
FROM BOOKING b
WHERE b.STATUS != 'CANCELLED'
GROUP BY TO_CHAR(b.BOOKING_TIME, 'YYYY-MM')
ORDER BY BOOKING_MONTH DESC;


-- 6. REPORT 3: PASSENGER TRAVEL HISTORY & LOYALTY PROFILE
SELECT 
    p.PASSENGER_ID,
    p.FIRST_NAME || ' ' || p.LAST_NAME AS PASSENGER_NAME,
    p.EMAIL,
    COUNT(b.BOOKING_ID) AS TOTAL_TRIPS_BOOKED,
    SUM(b.SEATS_BOOKED) AS TOTAL_SEATS_PURCHASED,
    NVL(SUM(b.TOTAL_FARE), 0) AS TOTAL_AMOUNT_SPENT
FROM PASSENGER p
LEFT JOIN BOOKING b ON p.PASSENGER_ID = b.PASSENGER_ID AND b.STATUS != 'CANCELLED'
GROUP BY p.PASSENGER_ID, p.FIRST_NAME, p.LAST_NAME, p.EMAIL
ORDER BY TOTAL_AMOUNT_SPENT DESC;


