-- Procedure 1: MAKE_BOOKING
-- Atomically books seats using SELECT ... FOR UPDATE to prevent race conditions.
CREATE OR REPLACE PROCEDURE MAKE_BOOKING (
    p_passenger_id IN NUMBER,
    p_trip_id      IN NUMBER,
    p_seats        IN NUMBER
) AS
    v_avail_seats  TRIP.AVAILABLE_SEATS%TYPE;
    v_route_id     TRIP.ROUTE_ID%TYPE;
    v_base_fare    ROUTE.BASE_FARE%TYPE;
    v_total_fare   NUMBER(10,2);
BEGIN
    -- Input validation
    IF p_seats <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Seat count must be at least 1.');
    END IF;

    -- Lock the trip record exclusively for concurrency protection
    SELECT AVAILABLE_SEATS, ROUTE_ID
    INTO v_avail_seats, v_route_id
    FROM TRIP
    WHERE TRIP_ID = p_trip_id
    FOR UPDATE;

    -- Check seat availability
    IF v_avail_seats < p_seats THEN
        RAISE_APPLICATION_ERROR(-20002, 'Not enough seats available. Available seats: ' || v_avail_seats);
    END IF;

    -- Fetch base fare
    SELECT BASE_FARE INTO v_base_fare
    FROM ROUTE
    WHERE ROUTE_ID = v_route_id;

    v_total_fare := v_base_fare * p_seats;

    -- Insert new booking (Trigger TRG_MANAGE_SEATS will update TRIP.AVAILABLE_SEATS)
    INSERT INTO BOOKING (
        BOOKING_ID, PASSENGER_ID, TRIP_ID, SEATS_BOOKED, TOTAL_FARE, STATUS, PAYMENT_STATUS, BOOKING_TIME
    ) VALUES (
        SEQ_BOOKING.NEXTVAL, p_passenger_id, p_trip_id, p_seats, v_total_fare, 'CONFIRMED', 'UNPAID', SYSDATE
    );

    COMMIT;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20003, 'Trip ID ' || p_trip_id || ' does not exist.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END MAKE_BOOKING;
/

-- Procedure 2: CANCEL_BOOKING
-- Safely cancels a booking and updates payment status
CREATE OR REPLACE PROCEDURE CANCEL_BOOKING (
    p_booking_id IN NUMBER
) AS
    v_status       BOOKING.STATUS%TYPE;
    v_pay_status   BOOKING.PAYMENT_STATUS%TYPE;
BEGIN
    SELECT STATUS, PAYMENT_STATUS
    INTO v_status, v_pay_status
    FROM BOOKING
    WHERE BOOKING_ID = p_booking_id
    FOR UPDATE;

    IF v_status = 'CANCELLED' THEN
        RAISE_APPLICATION_ERROR(-20004, 'Booking is already cancelled.');
    END IF;

    -- Update booking status (Trigger restores seats on TRIP)
    UPDATE BOOKING
    SET STATUS = 'CANCELLED',
        PAYMENT_STATUS = CASE WHEN v_pay_status = 'PAID' THEN 'REFUNDED' ELSE 'UNPAID' END,
        UPDATED_AT = SYSDATE
    WHERE BOOKING_ID = p_booking_id;

    COMMIT;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20006, 'Booking ID ' || p_booking_id || ' not found.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END CANCEL_BOOKING;
/

-- Procedure 3: UPDATE_COMPLETED_TRIPS
-- Updates trips to COMPLETED if their arrival time has passed
CREATE OR REPLACE PROCEDURE UPDATE_COMPLETED_TRIPS AS
BEGIN
    UPDATE TRIP
    SET STATUS = 'COMPLETED',
        UPDATED_AT = SYSDATE
    WHERE STATUS IN ('SCHEDULED', 'IN_PROGRESS')
      AND ARRIVAL_TIME <= CURRENT_TIMESTAMP;

    COMMIT;
END UPDATE_COMPLETED_TRIPS;
