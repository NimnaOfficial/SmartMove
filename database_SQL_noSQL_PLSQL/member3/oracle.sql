-- 8. REPORT 5: TRIP OPERATIONAL PERFORMANCE & SEAT OCCUPANCY
-- -------------------------------------------------------------------
-- Calculates seat occupancy percentage for each scheduled or completed trip
SELECT 
    t.TRIP_ID,
    r.ORIGIN || ' -> ' || r.DESTINATION AS ROUTE_NAME,
    t.STATUS AS TRIP_STATUS,
    v.CAPACITY AS TOTAL_CAPACITY,
    (v.CAPACITY - t.AVAILABLE_SEATS) AS BOOKED_SEATS,
    ROUND(((v.CAPACITY - t.AVAILABLE_SEATS) / v.CAPACITY) * 100, 1) AS OCCUPANCY_PERCENT
FROM TRIP t
JOIN ROUTE r ON t.ROUTE_ID = r.ROUTE_ID
JOIN VEHICLE v ON t.VEHICLE_ID = v.VEHICLE_ID
ORDER BY OCCUPANCY_PERCENT DESC;


